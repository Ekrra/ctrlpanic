import { FileText, X } from "lucide-react";
import { useLanguage } from "./LanguageProvider";
import { Button } from "./ui/button";
import { CodeEditor } from "./CodeEditor";
import { ResultsPanel } from "./ResultsPanel";
import { CompetitiveResults } from "./CompetitiveResults";
import { DEBUG_SAMPLES, REVIEW_SAMPLES, SOLVER_SAMPLES } from "@/lib/demo-samples";

function Block({ label, children }: { label: string; children: React.ReactNode }) {
  return <div className="min-w-0"><p className="mb-1 text-xs font-semibold text-muted-foreground">{label}</p>{children}</div>;
}
function Pre({ text }: { text: string }) {
  return <pre className="whitespace-pre-wrap break-words rounded-xl bg-code p-3 font-mono text-sm text-code-foreground">{text}</pre>;
}

/** Pre-written walkthrough shown when live AI is unavailable. Always labelled; never about the student's own input. */
export function OfflineSample({ mode, onClose }: { mode: "debug" | "solver" | "review"; onClose: () => void }) {
  const { t, language } = useLanguage();
  const debug = DEBUG_SAMPLES[language];
  const cp = mode === "review" ? REVIEW_SAMPLES[language] : SOLVER_SAMPLES[language];
  return <div className="grid gap-5" data-testid="offline-sample">
    <div role="note" className="flex gap-3 rounded-2xl border border-butter-foreground/20 bg-butter/40 p-4 text-sm">
      <FileText aria-hidden="true" className="mt-0.5 size-5 shrink-0" />
      <div className="min-w-0 flex-1">
        <p className="font-semibold">{t("Offline demo sample · Not live AI")}</p>
        <p className="mt-1 text-muted-foreground">{t("This walkthrough was written in advance by the CtrlPanic team to show how the tutor teaches. It is not generated by AI and is not about your input. Your own inputs above are unchanged.")}</p>
      </div>
      <Button type="button" variant="ghost" size="icon" onClick={onClose} aria-label={t("Close offline sample")} className="shrink-0"><X /></Button>
    </div>
    {mode === "debug" ? <>
      <div className="grid gap-4 md:grid-cols-2">
        <Block label={t("Sample Python code")}><div className="overflow-hidden rounded-xl bg-code"><CodeEditor value={debug.code} readOnly minHeight="60px" ariaLabel={t("Sample Python code")} /></div></Block>
        <Block label={t("Sample error message")}><Pre text={debug.error} /></Block>
      </div>
      <ResultsPanel analysis={debug.analysis} sample />
    </> : <>
      <div className="grid gap-4">
        {cp.statement && <Block label={t("Sample problem")}><p className="whitespace-pre-wrap rounded-xl border bg-card p-3 text-sm leading-relaxed">{cp.statement}</p></Block>}
        <div className="grid gap-4 sm:grid-cols-3">
          <Block label={t("Sample input")}><Pre text={cp.sampleInput} /></Block>
          <Block label={t("Sample output")}><Pre text={cp.sampleOutput} /></Block>
          <Block label={t("Constraints")}><Pre text={cp.constraints} /></Block>
        </div>
        {cp.code && <Block label={t("Sample student code")}><div className="overflow-hidden rounded-xl bg-code"><CodeEditor value={cp.code} readOnly minHeight="60px" ariaLabel={t("Sample student code")} /></div></Block>}
      </div>
      <CompetitiveResults analysis={cp.analysis} learnFirst={mode === "solver"} review={mode === "review"} sample />
    </>}
  </div>;
}
